//! Where ShellRS keeps its data on disk.

use std::path::{Path, PathBuf};
use std::sync::OnceLock;

/// Overrides the data directory. Set by tests and handy during development.
const DATA_DIR_ENV: &str = "SHELLRS_DATA_DIR";

/// The folder beside `shellrs.exe` that makes a Windows copy portable: its
/// data lives there instead of in the user's profile.
pub const PORTABLE_DATA: &str = "data";

/// What the Windows setup program leaves beside the copy it installed. Its
/// uninstaller deletes the whole folder, so a `data` folder there must not
/// hold anything.
pub const SETUP_UNINSTALLER: &str = "unins000.exe";

/// The directory holding ShellRS's own files, e.g.
/// `~/Library/Application Support/shellrs` on macOS: `SHELLRS_DATA_DIR`,
/// else a portable copy's `data` folder (one beside the program, on every
/// system), else the system's place for application data. Falls back to the current directory on the platforms
/// where `dirs` has nothing to offer.
pub fn data_dir() -> PathBuf {
    if let Some(dir) = std::env::var_os(DATA_DIR_ENV) {
        return PathBuf::from(dir);
    }
    if let Some(root) = portable_root() {
        return root.join(PORTABLE_DATA);
    }
    dirs::data_dir()
        .map(|dir| dir.join("shellrs"))
        .unwrap_or_else(|| PathBuf::from("."))
}

/// Where everything ShellRS keeps is, sealed with the app lock password:
/// the vault's folder in the data directory.
pub fn vault_dir() -> PathBuf {
    data_dir().join("vault")
}

/// The file holding the hosts database, which runs in memory.
pub fn database_path() -> PathBuf {
    vault_dir().join("shellrs.db")
}

/// The file holding the keys of the hosts ShellRS trusts.
pub fn known_hosts_path() -> PathBuf {
    vault_dir().join("known_hosts")
}

/// Where the private keys pasted into or generated by the credential form
/// are kept, beside the database. Created when the first one is saved.
pub fn keys_dir() -> PathBuf {
    vault_dir().join("keys")
}

/// Where the saved local terminals' last output is kept, a file each,
/// beside the database. Created when the first is kept.
pub fn terminal_output_dir() -> PathBuf {
    vault_dir().join("terminal-output")
}

/// Where updates are downloaded to: the user's cache folder. With
/// `SHELLRS_DATA_DIR` set it is beside the data instead, so a test or
/// development instance never shares downloads with the installed app; so
/// it is for a portable copy, which then leaves nothing in the profile and
/// unpacks its update on the volume it runs from.
pub fn updates_dir() -> PathBuf {
    if std::env::var_os(DATA_DIR_ENV).is_some() || portable_root().is_some() {
        return data_dir().join("updates");
    }
    dirs::cache_dir()
        .map(|dir| dir.join("shellrs").join("updates"))
        .unwrap_or_else(|| data_dir().join("updates"))
}

/// The interface settings, a small JSON file beside the database.
pub fn settings_path() -> PathBuf {
    vault_dir().join("settings.json")
}

/// The main window's last size, maximized state and place, for the next
/// launch (设置 › 应用 › 窗口). Kept apart from the settings: it changes
/// whenever the window moves.
pub fn window_state_path() -> PathBuf {
    data_dir().join("window.json")
}

/// What 撰写窗格 sent, for ↑ and ↓ to go back to after a restart, as a
/// shell's history file. Beside the settings, on this computer only.
pub fn compose_history_path() -> PathBuf {
    vault_dir().join("compose-history.json")
}

/// Where the running app listens for a ShellRS opened again on the same
/// data.
pub fn instance_socket_path() -> PathBuf {
    instance_endpoint(&data_dir())
}

/// Where an app keeping its data in `dir` listens for one opened again: a
/// socket in that directory, or on Windows a named pipe.
///
/// Pipe names are one namespace for the whole machine, so the name is made
/// from the data directory. That usually lives in the user's profile, so
/// each user, each `SHELLRS_DATA_DIR` and each portable folder gets a pipe
/// of its own; two users running one portable folder would share it.
pub fn instance_endpoint(dir: &Path) -> PathBuf {
    if cfg!(windows) {
        PathBuf::from(pipe_name(dir))
    } else {
        dir.join("instance.sock")
    }
}

/// The folder a portable copy of ShellRS runs from: the one holding the
/// program and a `data` folder. Looked up once; `None` for an installed
/// copy.
pub fn portable_root() -> Option<&'static Path> {
    static ROOT: OnceLock<Option<PathBuf>> = OnceLock::new();
    ROOT.get_or_init(|| {
        // The path as the system spells it: a short 8.3 name or another
        // letter case would give a copy opened again another pipe.
        let exe = std::env::current_exe().ok()?;
        let exe = dunce::canonicalize(&exe).unwrap_or(exe);
        let appimage = std::env::var_os("APPIMAGE").map(PathBuf::from);
        portable_root_of(&program(&exe, appimage.as_deref()))
    })
    .as_deref()
}

/// What the user sees as the program, and moves as one thing: the Linux
/// AppImage, the macOS app bundle, else the executable itself.
fn program(exe: &Path, appimage: Option<&Path>) -> PathBuf {
    if let Some(appimage) = appimage {
        return appimage.to_path_buf();
    }
    exe.ancestors()
        .find(|path| path.extension().is_some_and(|extension| extension == "app"))
        .unwrap_or(exe)
        .to_path_buf()
}

/// The portable folder `exe` belongs to: its own folder when that has a
/// `data` folder of ShellRS's. Never a folder the setup program installed
/// into.
pub(crate) fn portable_root_of(exe: &Path) -> Option<PathBuf> {
    let root = exe.parent()?;
    (is_portable_data(&root.join(PORTABLE_DATA)) && !root.join(SETUP_UNINSTALLER).exists())
        .then(|| root.to_path_buf())
}

/// Whether `data` is a folder ShellRS may keep its data in: an empty one,
/// or one it has used. Someone else's `data` folder that happens to be
/// beside the program (in Downloads, in `/usr/bin`) is left alone.
fn is_portable_data(data: &Path) -> bool {
    const OURS: [&str; 3] = ["vault", "window.json", "instance.sock"];
    let Ok(entries) = std::fs::read_dir(data) else {
        return false;
    };
    let names: Vec<_> = entries.flatten().map(|entry| entry.file_name()).collect();
    // On Windows a data folder is what the portable package ships, and
    // may hold what an earlier version kept there.
    cfg!(windows)
        || names.is_empty()
        || names
            .iter()
            .any(|name| OURS.iter().any(|ours| name == ours))
}

/// `\\.\pipe\shellrs-instance-` and a hash of the directory. Windows paths
/// ignore case, so the hash does too.
fn pipe_name(dir: &Path) -> String {
    use sha2::{Digest as _, Sha256};

    let dir = std::path::absolute(dir).unwrap_or_else(|_| dir.to_path_buf());
    let digest = Sha256::digest(dir.to_string_lossy().to_lowercase().as_bytes());
    let hex: String = digest[..8]
        .iter()
        .map(|byte| format!("{byte:02x}"))
        .collect();
    format!(r"\\.\pipe\shellrs-instance-{hex}")
}

#[cfg(test)]
mod tests {
    use std::fs;
    use std::path::Path;

    use super::{PORTABLE_DATA, SETUP_UNINSTALLER, pipe_name, portable_root_of};

    #[test]
    fn a_data_folder_beside_the_program_makes_it_portable() {
        let root = tempfile::tempdir().unwrap();
        let exe = root.path().join("shellrs.exe");
        fs::write(&exe, "").unwrap();
        assert_eq!(portable_root_of(&exe), None);
        fs::create_dir(root.path().join(PORTABLE_DATA)).unwrap();
        assert_eq!(portable_root_of(&exe).as_deref(), Some(root.path()));
    }

    #[test]
    fn the_program_is_the_appimage_or_the_app_bundle_when_there_is_one() {
        let exe = Path::new("/tmp/.mount_ShellRabc/usr/bin/shellrs");
        let appimage = Path::new("/home/me/tools/ShellRS.AppImage");
        assert_eq!(super::program(exe, Some(appimage)), appimage);
        assert_eq!(super::program(exe, None), exe);
        let exe = Path::new("/Volumes/Stick/ShellRS.app/Contents/MacOS/shellrs");
        assert_eq!(
            super::program(exe, None),
            Path::new("/Volumes/Stick/ShellRS.app")
        );
    }

    #[cfg(not(windows))]
    #[test]
    fn someone_elses_data_folder_is_not_taken() {
        let root = tempfile::tempdir().unwrap();
        let exe = root.path().join("ShellRS.AppImage");
        let data = root.path().join(PORTABLE_DATA);
        fs::create_dir(&data).unwrap();
        fs::write(data.join("holiday.csv"), "").unwrap();
        assert_eq!(portable_root_of(&exe), None);
        fs::create_dir(data.join("vault")).unwrap();
        assert_eq!(portable_root_of(&exe).as_deref(), Some(root.path()));
    }

    #[test]
    fn a_file_named_data_is_not_a_data_folder() {
        let root = tempfile::tempdir().unwrap();
        fs::write(root.path().join(PORTABLE_DATA), "").unwrap();
        assert_eq!(portable_root_of(&root.path().join("shellrs.exe")), None);
    }

    #[test]
    fn an_installed_copy_never_turns_portable() {
        let root = tempfile::tempdir().unwrap();
        fs::create_dir(root.path().join(PORTABLE_DATA)).unwrap();
        fs::write(root.path().join(SETUP_UNINSTALLER), "").unwrap();
        assert_eq!(portable_root_of(&root.path().join("shellrs.exe")), None);
    }

    #[test]
    fn each_data_directory_gets_a_pipe_of_its_own() {
        let pipe = pipe_name(Path::new("/Users/me/AppData/Roaming/shellrs"));
        assert!(pipe.starts_with(r"\\.\pipe\shellrs-instance-"));
        assert_eq!(pipe.len(), r"\\.\pipe\shellrs-instance-".len() + 16);
        assert_eq!(
            pipe,
            pipe_name(Path::new("/USERS/me/appdata/Roaming/SHELLRS"))
        );
        assert_ne!(
            pipe,
            pipe_name(Path::new("/Users/other/AppData/Roaming/shellrs"))
        );
    }
}
